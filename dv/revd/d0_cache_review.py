"""Read-only inventory of Python bytecode side effects and rejected restoration."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import sys
import uuid

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
REJECTED_COMMAND = r"""$artifactDir = 'D:\github\kwt\reports\revd\d0\cache_restore\20261017T050600Z'
New-Item -ItemType Directory -Path $artifactDir -ErrorAction Stop | Out-Null
$paths = @('D:\github\kwt\docs\revd\tools\__pycache__\core_model.cpython-312.pyc', 'D:\github\kwt\numeric\__pycache__\artifacts.cpython-312.pyc')
$records = @()
foreach ($path in $paths) {
    $resolved = (Resolve-Path -LiteralPath $path -ErrorAction Stop).Path
    if (-not $resolved.StartsWith('D:\github\kwt\', [System.StringComparison]::OrdinalIgnoreCase)) { throw 'Cache path escaped workspace' }
    $digest = (Get-FileHash -LiteralPath $resolved -Algorithm SHA256).Hash.ToLowerInvariant()
    Move-Item -LiteralPath $resolved -Destination $artifactDir -ErrorAction Stop
    $records += [ordered]@{original=$resolved; sha256=$digest; action='Moved only known D0-generated bytecode to evidence; no source change'}
}
if (@(Get-ChildItem -LiteralPath 'D:\github\kwt\docs\revd\tools\__pycache__' -Force).Count -eq 0) { Remove-Item -LiteralPath 'D:\github\kwt\docs\revd\tools\__pycache__' -ErrorAction Stop }
$records | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath ($artifactDir + '\restore_record.json') -Encoding utf8
$records | ConvertTo-Json -Depth 5
python -B -X utf8 dv/revd/d0_run.py"""


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def inspect():
    launch = json.loads((ROOT / "work/revd/launch_baseline.json").read_text(encoding="utf-8"))
    snapshot = json.loads((ROOT / "work/revd/source_snapshot.json").read_text(encoding="utf-8"))
    tracked = launch["tracked_file_sha256"]
    snapshot_files = {"docs/revd/" + item["path"]: item["sha256"] for item in snapshot["files"]}
    extras = []
    for prefix in ("docs/revd", "numeric"):
        for path in sorted((ROOT / prefix).rglob("*")):
            if not path.is_file():
                continue
            name = path.relative_to(ROOT).as_posix()
            known = snapshot_files if prefix == "docs/revd" else tracked
            if name in known:
                continue
            stat = path.stat()
            created = getattr(stat, "st_birthtime", stat.st_ctime)
            extras.append({"path": name, "sha256": sha(path), "bytes": stat.st_size,
                           "created_utc": datetime.fromtimestamp(created, timezone.utc).isoformat(),
                           "modified_utc": datetime.fromtimestamp(stat.st_mtime, timezone.utc).isoformat(),
                           "in_launch_baseline": name in tracked,
                           "in_revd_snapshot": name in snapshot_files,
                           "interpretation": "new this trial by creation time; not an original source entry"})
    return {"checked_utc": datetime.now(timezone.utc).isoformat(), "operation": "READ_ONLY",
            "restoration_attempt": {"tool": "exec_command", "shell": "powershell", "cwd": str(ROOT),
                                    "command": REJECTED_COMMAND, "executed": False,
                                    "rejection_reason_verbatim": "blocked by policy",
                                    "effect": "No requested mkdir/move/remove or subsequent D0 rerun executed"},
            "launch_baseline_sha256": sha(ROOT / "work/revd/launch_baseline.json"),
            "snapshot_receipt_sha256": sha(ROOT / "work/revd/source_snapshot.json"),
            "original_snapshot_hashes_match": all(sha(ROOT / name) == expected for name, expected in snapshot_files.items()),
            "extra_files": extras,
            "requested_restore_paths": ["docs/revd/tools/__pycache__/core_model.cpython-312.pyc",
                                        "numeric/__pycache__/artifacts.cpython-312.pyc"],
            "action_after_rejection": "No retry or alternate mutation. D0 uses dont_write_bytecode and -B; parent decides strictly bound restoration."}


if __name__ == "__main__":
    report = inspect()
    out = ROOT / "reports/revd/d0/cache_review" / (
        datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "_" + uuid.uuid4().hex[:8])
    out.mkdir(parents=True, exist_ok=False)
    path = out / "review.json"
    path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({"report": path.relative_to(ROOT).as_posix(), "extra_files": report["extra_files"]}))
